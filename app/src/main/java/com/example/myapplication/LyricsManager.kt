    // ── 文件名 → 搜索关键词 ──

    fun extractKeyword(filename: String): String {
        val nameNoExt = filename.substringBeforeLast('.')
        // 先尝试 "Artist - Title" 分割
        for (sep in listOf(" - ", " – ", "—")) {
            val idx = nameNoExt.indexOf(sep)
            if (idx > 0) {
                val title = nameNoExt.substring(idx + sep.length).trim()
                if (title.isNotEmpty()) return cleanKeyword(title)
            }
        }
        // 按连续空格分割，取后半部分作为 title
        val parts = nameNoExt.split(Regex("""\s{2,}"""))
        return if (parts.size >= 2) {
            cleanKeyword(parts.drop(1).joinToString(" "))
        } else {
            cleanKeyword(nameNoExt)
        }
    }

    private fun cleanKeyword(raw: String): String {
        var kw = raw
            .replace("_", " ")
            .replace("-", " ")
            .replace(Regex("""[【】「」\(\)\[\]（）]"""), " ")
        // 移除纯数字/日期片段（如 20250609、143025、1845 等，但保留年份范围 1980-2050）
        kw = kw.replace(Regex("""\b\d{6,14}\b"""), " ")
        // 移除过短的数字片段（3-5位，通常是时间编号而非歌曲名）
        kw = kw.replace(Regex("""\b\d{3,5}\b"""), " ")
        kw = kw.replace(Regex("""\s+"""), " ").trim()
        // 如果处理后只剩下很少的字符，可能是无效搜索词
        return kw
    }

    /**
     * 从文件名中尝试提取歌手名。
     * 支持格式："Artist - Title.mp3"、"Artist  Title.mp3"（多个空格分隔）
     * 返回提取到的歌手名，匹配不到时返回空串。
     */
    fun extractArtistFromFilename(filename: String): String {
        val nameNoExt = filename.substringBeforeLast('.')
        // 按 " - " 或 " – " 分割（带空格横线优先）
        for (sep in listOf(" - ", " – ", "—")) {
            val idx = nameNoExt.indexOf(sep)
            if (idx > 0) {
                val artist = nameNoExt.substring(0, idx).trim()
                if (artist.isNotEmpty()) return artist
            }
        }
        // 回退：按连续空格分割，取第一段
        val parts = nameNoExt.split(Regex("""\s{2,}"""))
        return if (parts.size >= 2) parts[0].trim() else ""
    }
