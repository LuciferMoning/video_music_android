object LyricsManager {

    data class LyricLine(val timeMs: Long, val text: String)
    data class SongResult(val id: String, val name: String, val artist: String, val cover: String = "")

    /**
     * 通过 lrc.cx API 搜索歌词（含降级重试）。
     * 首次搜索失败后自动移除数字串重试。
     * callback(result, lrcText, errorMessage) — lrcText 与 errorMessage 二选一非空。
     */
    fun searchLyrics(songName: String, artist: String, callback: (SongResult?, String?, String?) -> Unit) {
        thread {
            val result = doSearchLyrics(songName, artist)
            if (result != null) {
                callback(null, result, null)
                return@thread
            }
            // 首次失败，降级：移除数字串后重试
            val fallback = songName.replace(Regex("""\d+"""), " ").replace(Regex("""\s+"""), " ").trim()
            if (fallback.isNotEmpty() && fallback != songName) {
                Log.d("Lyrics", "降级搜索: $songName → $fallback")
                val retryResult = doSearchLyrics(fallback, artist)
                if (retryResult != null) {
                    callback(null, retryResult, null)
                    return@thread
                }
            }
            callback(null, null, "未找到匹配歌词，可尝试手动搜索")
        }
    }

    private fun doSearchLyrics(title: String, artist: String): String? {
        return try {
            val encodedTitle = URLEncoder.encode(title, "UTF-8")
            val encodedArtist = URLEncoder.encode(artist, "UTF-8")
            val url = URL("https://api.lrc.cx/lyrics?artist=$encodedArtist&title=$encodedTitle")
            Log.d("Lyrics", "API请求: $url")
            val conn = (url.openConnection() as HttpURLConnection).apply {
                connectTimeout = 10000
                readTimeout = 10000
                requestMethod = "GET"
                setRequestProperty("User-Agent", "Mozilla/5.0 (Windows NT 10.0; Win64; x64)")
            }

            val code = conn.responseCode
            Log.d("Lyrics", "API响应码: $code")
            if (code != 200) return null

            val body = conn.inputStream.bufferedReader().readText()
            val trimmed = body.trim()
            Log.d("Lyrics", "API响应体前80字: ${trimmed.take(80)}")

            if (trimmed.isEmpty() || (!trimmed.startsWith("[") && !trimmed.contains(Regex("""\[\d{1,3}:\d{2}""")))) {
                Log.d("Lyrics", "API响应不是LRC格式")
                null
            } else {
                trimmed
            }
        } catch (e: Exception) {
            Log.e("Lyrics", "API请求异常: ${e.javaClass.simpleName}: ${e.message}")
            null
        }
    }

    /** 解析 LRC 格式歌词 */
    fun parseLrc(lrcText: String): List<LyricLine> {
        val lines = mutableListOf<LyricLine>()
        val regex = Regex("""\[(\d{1,3}):(\d{2})(?:[.](\d{1,3}))?]\s*(.*)""")
        for (line in lrcText.lines()) {
            val match = regex.find(line) ?: continue
            val min = match.groupValues[1].toInt()
            val sec = match.groupValues[2].toInt()
            val msRaw = match.groupValues[3]
            val ms = if (msRaw.isNotEmpty()) {
                msRaw.padEnd(3, '0').take(3).toInt()
            } else 0
            val text = toSimple(match.groupValues[4].trim())
            if (text.isNotEmpty()) {
                lines.add(LyricLine(min * 60000L + sec * 1000L + ms, text))
            }
        }
        return lines.sortedBy { it.timeMs }
    }

    // ── 缓存 ──

    private fun cacheDir(context: Context): File {
        val dir = File(context.cacheDir, "lyrics")
        if (!dir.exists()) dir.mkdirs()
        return dir
    }

    private fun cacheKey(keyword: String): String = keyword.hashCode().toString()

    fun cacheLrc(context: Context, keyword: String, lrcContent: String) {
        File(cacheDir(context), cacheKey(keyword)).writeText(lrcContent)
    }

    fun getCachedLrc(context: Context, keyword: String): String? {
        val file = File(cacheDir(context), cacheKey(keyword))
        return if (file.exists()) file.readText() else null
    }

    fun clearCache(context: Context) {
        cacheDir(context).listFiles()?.forEach { it.delete() }
    }

